"""Zerescas Dreamcast registration and native optical scene data (MIT code)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
Q = 1.3
URL = 'https://sketchfab.com/3d-models/sega-dreamcast-f82d99e4739e42f4abfc37cb97918cfc'


def apply_specs(table):
    table['dreamcast'] = dict(kind=6, rx=190*Q/2, ry=195*Q/2, depth=80*Q/2,
        slot=0, mouth=0, cart=120*Q, sink=0, idle=540, origin=330, radius=0,
        colour=(202,202,196), yscale=1, entry=0)


def native_header():
    path = ROOT / 'theme/art-book-slot/_slot/consoles/dreamcast/registration.json'
    reg = json.loads(path.read_text())
    def array(name, values):
        return 'static const double '+name+'[]={'+','.join(f'{v:.9f}' for v in values)+'};'
    (ROOT / 'tools/slotlaunch/dreamcast-data.h').write_text(
        '/* Generated by tools.consolebuild.dreamcast; source registration, MIT. */\n'
        + array('dreamcast_hinge', reg['hinge_native'])+'\n'
        + array('dreamcast_disc_centre', reg['disc_centre_native'])+'\n'
        + f'static const double dreamcast_disc_radius={60*Q:.9f};\n'
        + f'static const double dreamcast_disc_tilt={reg["disc_tilt_radians"]:.14g};\n', newline='\n')


if __name__ == '__main__':
    native_header()
