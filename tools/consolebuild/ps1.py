"""PlayStation physical registration and original identifying print (MIT)."""
SPECS={'psx':dict(size=(270,60,188),scale=1.6,origin=304,   # raised 16 px: the standard 22-degree turn adds depth below the footprint
                  creator='darkigorek-ps1')}
COLORS={'ps1case':(.72,.72,.70),'ps1well':(.21,.215,.22),
        'ps1drive':(.12,.125,.135),'ps1socket':(.08,.085,.09)}

def palette(m):
    for name,rgb in COLORS.items():m.material(name,rgb)

def apply_specs(table):
    s=SPECS['psx'];w,h,d=s['size'];q=s['scale']
    table['psx']=dict(kind=6,rx=w*q/2,ry=d*q/2,depth=h*q/2,slot=0,
        mouth=0,cart=120*q,sink=0,idle=540,origin=s['origin'],radius=0,
        colour=(184,184,179),yscale=1,entry=0)

def registration():
    import json
    from pathlib import Path
    return json.loads((Path(__file__).resolve().parents[2]/'third_party/models/darkigorek-ps1/source.json').read_text())['registration']

def native_header():
    from pathlib import Path
    import json
    r=registration();q=SPECS['psx']['scale']
    folder=Path(__file__).resolve().parents[2]/'theme/art-book-slot/_slot/consoles/psx'
    if (folder/'model.texture').exists() and (folder/'registration.json').exists():
        textured=json.loads((folder/'registration.json').read_text())
        r=dict(r,hinge_xyz_mm=[v/q for v in textured['hinge_native']],
               disc_label_xyz_mm=[v/q for v in textured['disc_centre_native']])
    p=Path(__file__).resolve().parents[2]/'tools/slotlaunch/ps1-data.h'
    def array(name,values):return 'static const double '+name+'[]={'+','.join(f'{v*q:.9f}' for v in values)+'};'
    p.write_text('/* Generated by tools.consolebuild.ps1; measured source registration, MIT. */\n'+
        array('ps1_hinge',r['hinge_xyz_mm'])+'\n'+
        array('ps1_disc_centre',r['disc_label_xyz_mm'])+'\n'+
        f'static const double ps1_disc_radius={60*q:.9f};\n',newline='\n')

def console(m):
    palette(m);m.authored_geometry('psx')
    # Source print was image-based. Minimal identifying words are original
    # vectors, with no source texture, logo trace or game-art contribution.
    r=registration();q=SPECS['psx']['scale'];before=set(m.bpy.context.scene.objects)
    from mathutils import Vector
    m.bpy.context.view_layer.update()
    for value,x,z,size,moving in (('SONY',-30,-43,5,True),
            ('PlayStation',0,8,4.5,True),('POWER',-103,51,2.5,False),
            ('RESET',-106,15,1.8,False),('OPEN',103,51,2.5,False)):
        hit,p,*_=m.bpy.context.scene.ray_cast(m.bpy.context.evaluated_depsgraph_get(),
            Vector(m.xyz(x*q,80*q,z*q)),Vector((0,0,-1)))
        if not hit:raise RuntimeError('PS1 identifying print has no supporting surface: '+value)
        name=m.text(value,(x,p.z/(q*m.SCALE)+.09,z),size,m.M['ink'])
        name['hinged']=moving
    m.uniform_group(before,q)
