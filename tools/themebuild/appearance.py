"""Console enclosure masks and appearance options; no ROM/media processing (MIT)."""
import hashlib,json,struct
from pathlib import Path
import numpy as np

COLORS={'original':None,'black':(.105,.115,.135),'white':(.88,.89,.87),
        'red':(.72,.12,.17),'blue':(.14,.32,.72),'purple':(.43,.24,.68),
        'green':(.13,.49,.31),'yellow':(.88,.67,.16)}
STYLES=('realistic','cel')
# Finish is available to every native console. Paint eligibility is separate:
# older procedural families keep their original enclosure colours.
STYLE_MODELS=('gb','gbc','gba','nds','psp','pico8','snes','snes-us','nes','n64','md','md-jp','psx','dreamcast')
PAINT={
 'gb':('DMG recreation housing',),
 'gbc':('CGB housing','CGB battery cover'),
 'gba':('SP display lid','SP recreation housing','SP Top_LargeHinge','SP Top_SmallHinge',
        'SP Battery_Lid','SP HingeCorner_RMid','SP HingeCorner_LMid','SP bay floor'),
 'psp':('PSP recreation housing','UMD door shell'),
 'snes':('PAL inset panel','PAL left enclosure shoulder','PAL rear enclosure shoulder',
         'PAL right enclosure shoulder','PAL front enclosure fascia','PAL upper enclosure',
         'PAL lower enclosure','PAL underside enclosure','PAL controller fascia'),
 'snes-us':('US upper enclosure','US lower enclosure'),
 'n64':('N64 upper enclosure','N64 lower enclosure','N64 memory expansion door'),
 'psx':('PS1 enclosure','PS1 disc lid'),
 'dreamcast':('Dreamcast enclosure','Dreamcast disc lid','Dreamcast rear hinge cover'),
}

def vertex_hash(data):
    h=14695981039346656037
    for b in data:h=((h^b)*1099511628211)&0xffffffffffffffff
    return h

def glb_positions(path):
    raw=path.read_bytes();length=struct.unpack_from('<I',raw,12)[0]
    g=json.loads(raw[20:20+length]);binary=28+length
    for node in g['nodes']:
        if 'mesh' not in node:continue
        for p in g['meshes'][node['mesh']]['primitives']:
            a=g['accessors'][p['attributes']['POSITION']];v=g['bufferViews'][a['bufferView']]
            start=binary+v.get('byteOffset',0)+a.get('byteOffset',0)
            points=np.ndarray((a['count'],3),'<f4',raw,start,strides=(v.get('byteStride',12),4))
            yield node['name'],points*100

def paint_mask(folder):
    raw=(folder/'model.mesh').read_bytes();n=struct.unpack_from('<I',raw,8)[0]
    vertices=np.frombuffer(raw,'<f4',n*9,20).reshape(-1,9)
    if (folder/'model.texture').exists():
        # Textured sources: tools.consolebuild.textured derives the fallback
        # weights from the albedo's paint alpha. Verify, never regenerate here.
        mask=(folder/'paint.mask').read_bytes();h=vertex_hash(raw[20:20+n*36])
        assert mask[:8]==b'SCPAINT1' and struct.unpack_from('<IQ',mask,8)==(n,h),(folder.name,'Stale textured paint mask')
        return dict(vertices=n,painted_vertices=int(sum(1 for w in mask[20:] if w)),parts='albedo paint alpha',
                    mesh_sha256=hashlib.sha256(raw).hexdigest(),vertex_fnv1a64=f'{h:016x}')
    parts={};points=set()
    for name,positions in glb_positions(folder/'model.glb'):
        if any(name==p or name.startswith(p+'.') for p in PAINT[folder.name]):
            parts[name]=len(positions)
            points.update(tuple(p) for p in np.round(positions,3))
    selected=np.array([tuple(p) in points for p in np.round(vertices[:,:3],3)])
    if folder.name in ('snes','snes-us','n64'):
        # Authored sources share enclosure/control boundary positions. Match the
        # enclosure palette too so those corners cannot paint the controls.
        from ..consolebuild import snes,n64
        family=n64 if folder.name=='n64' else snes
        colours=[family.COLORS[p] for p in family.ENCLOSURE_PALETTES[folder.name]]
        selected &= np.any([np.max(np.abs(vertices[:,6:9]-rgb),axis=1)<.005 for rgb in colours],axis=0)
    assert selected.sum()>100,(folder.name,'Empty enclosure paint mask')
    brightness=vertices[:,6:9].mean(axis=1)
    anchor=float(np.median(brightness[selected]))
    weights=np.where(selected,np.round(np.clip(brightness/max(anchor,.001),.55,1.25)*192),0).astype('uint8')
    h=vertex_hash(raw[20:20+n*36])
    (folder/'paint.mask').write_bytes(struct.pack('<8sIQ',b'SCPAINT1',n,h)+weights.tobytes())
    return dict(vertices=n,painted_vertices=int(selected.sum()),parts=parts,
                mesh_sha256=hashlib.sha256(raw).hexdigest(),vertex_fnv1a64=f'{h:016x}')

def build(slot):
    slot=Path(slot);out=slot/'appearance';out.mkdir(exist_ok=True)
    report={name:paint_mask(slot/'consoles'/name) for name in PAINT}
    (out/'manifest.json').write_text(json.dumps(dict(styles=STYLES,colors=COLORS,models=report,style_models=STYLE_MODELS),indent=2)+'\n')
    header=['/* Generated by tools.themebuild.appearance, MIT. */',
            'static const ConsolePaint console_paints[]={']
    header += ['    {"'+name+'",{'+','.join(f'{c:.6f}f' for c in rgb)+'}},' for name,rgb in COLORS.items() if rgb]
    header += ['};','static const char *console_appearance_models[]={'+','.join('"'+s+'"' for s in PAINT)+'};',
               'static const char *console_style_models[]={'+','.join('"'+s+'"' for s in STYLE_MODELS)+'};','']
    (Path(__file__).resolve().parents[2]/'tools/slotlaunch/appearance-data.h').write_text('\n'.join(header))
    for kind,values in (('style',STYLES),('color',COLORS)):
        for value in values:
            key='slotModelStyle' if kind=='style' else 'slotConsoleColor'
            (out/(kind+'-'+value+'.xml')).write_text(
                '<?xml version="1.0" encoding="UTF-8"?>\n<theme><formatVersion>7</formatVersion>'
                f'<variables><{key}>{value}</{key}></variables></theme>\n')
    from xml.sax.saxutils import escape
    system='{system:theme}'
    expression='"gb"'
    snes_region='(contains(upper({game:path}), "(USA") || contains(upper({game:path}), "(CANADA")) ? "snes-us" : "snes"'
    choices=[(('gb','gbh'),'"gb"'),(('gbc','gbch'),'"gbc"'),(('gba','gbah'),'"gba"'),
      (('psp',),'"psp"'),(('snes',),snes_region),(('snes-us',),'"snes-us"'),(('n64','n64h'),'"n64"'),
      (('nds',),'"nds"'),(('nes',),'"nes"'),(('pico8',),'"pico8"'),(('psx',),'"psx"'),(('dreamcast',),'"dreamcast"'),
      (('megadrive','genesis','md'),'contains(upper({game:path}), "JAPAN") && !contains(upper({game:path}), "USA") && !contains(upper({game:path}), "EUROPE") ? "md-jp" : "md"'),
      (('md-jp',),'"md-jp"')]
    ready=' || '.join(system+' == "'+s+'"' for aliases,value in choices for s in aliases)
    for aliases,value in reversed(choices):
        condition=' || '.join(system+' == "'+s+'"' for s in aliases)
        expression='('+condition+') ? ('+value+') : ('+expression+')'
    path='('+ready+') ? ("${currentPath}/${slotModelStyle}/${slotConsoleColor}/band-console-" + ('+expression+') + ".png") : ""'
    (out/'shelf.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n'
       '<theme><formatVersion>7</formatVersion><view name="gamecarousel">'
       '<image name="slot-console-appearance" extra="true"><pos>0 0.879167</pos>'
       '<size>1 0.120833</size><path>'+escape(path)+'</path><visible>'+escape(ready)+'</visible><zIndex>30.1</zIndex>'
       '</image></view></theme>\n')
    return report

if __name__=='__main__':
    root=Path(__file__).resolve().parents[2]
    print(json.dumps(build(root/'theme/art-book-slot/_slot'),indent=2))
