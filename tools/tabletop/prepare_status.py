"""Bake the existing CC0 Raster Forge status glyphs at their native 8px grid.

Generated masks are extruded into real geometry by SlotVoxel.h, never rendered
as image plates. Pillow is needed only for this reproducible source preparation.
"""
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / 'theme/art-book-slot/_slot/fonts/RasterForge.ttf'
OUT = ROOT / 'tools/frontend/overlay/es-app/src/components/SlotStatusGlyphs.h'


def main():
    font = ImageFont.truetype(str(FONT), 8)
    lines = ['// Generated by tools/tabletop/prepare_status.py; Raster Forge (CC0).',
             '// Source SHA-256: ' + hashlib.sha256(FONT.read_bytes()).hexdigest(),
             '#pragma once', '#include <cstdint>', 'namespace slot_scene {',
             'struct StatusGlyph {char code;int advance,width;uint16_t rows[5];};',
             'static constexpr StatusGlyph statusGlyphs[]={']
    for char in '0123456789:%-?':
        width = round(font.getlength(char))
        assert width <= 16, (char, width)
        mask = Image.new('L', (width, 8))
        ImageDraw.Draw(mask).text((0, 0), char, font=font, fill=255)
        rows = [sum((1 << x) for x in range(width) if mask.getpixel((x, y + 1)) >= 128)
                for y in range(5)]
        lines.append("    {'%s',%d,%d,{%s}}," %
                     (char, round(font.getlength(char)), width, ','.join(map(str, rows))))
    lines.extend(['};', '}'])
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Prepared native-grid status glyphs:', OUT.relative_to(ROOT))


if __name__ == '__main__':
    main()
