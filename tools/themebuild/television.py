"""Crop each prepared TV render and register its live screen; no game artwork.

Profiles are selected by the theme setting `slot-tv-model`; the first is the
default and the fallback for an unknown or missing value. The prepared models come from
tools/consolebuild/import_tv.py (Panasonic), import_retro_tv.py (Retro TV) and import_old_tv.py (Old TV); the
renders from render_tv_standard.py, at the scene's standard view angle and in the native
renderer's own perspective (35 degree elevation, cabinet turned 22 degrees). Each profile
registers the live glass quad (projected onto the angled glass), the floor contact point and
the footprint, in logical scene pixels, so the frontend can stand the cabinet on the same
floor line as the console beside it.
"""
import hashlib,json
from PIL import Image
from .geometry import ROOT
from .stage import save_changed

# id, display label, prepared-model folder (provenance only)
PROFILES=(('panasonic','Panasonic CRT (DamianToons, CC BY 4.0)','damiantoons-panasonic'),
          ('retro','Retro TV (Denys Hroshko, CC BY-NC 4.0)','denys-retro-tv'),
          ('pvm','Sony PVM-1341 (dark_igorek, CC BY 4.0)','darkigorek-pvm'),
          ('oldtv','Old TV 14-inch (pibanezl, CC BY 4.0)','pibanezl-old-tv'))


def prepare(identifier,label,family):
    source=ROOT/'build/slotted-presentation'
    profile=json.loads((source/f'{identifier}-source.json').read_text())
    out=ROOT/'theme/art-book-slot/_slot/stage/tv';out.mkdir(parents=True,exist_ok=True)
    with Image.open(source/f'{identifier}-render.png') as image:
        bounds=image.getchannel('A').getbbox()
        if not bounds or min(bounds)<=0 or bounds[2]>=image.width or bounds[3]>=image.height:
            raise ValueError(f'{identifier} TV housing is clipped')
        crop=image.crop(bounds);save_changed(crop,out/f'{identifier}.png')
    quad=[[(x-bounds[0])/crop.width,(y-bounds[1])/crop.height] for x,y in profile.pop('quad_pixels')]
    if not all(0<v<1 for point in quad for v in point):
        raise ValueError(f'{identifier} live screen leaves the TV render')
    profile.pop('glass_bounds_pixels',None)
    scale=profile.get('render_scale',1)           # image pixels per logical scene pixel
    display=[crop.width/scale,crop.height/scale]
    base_pixels=profile.pop('base_pixels',[bounds[0]+crop.width/2,bounds[3]])
    feet=profile.pop('footprint_pixels',[[bounds[0],bounds[3]],[bounds[2],bounds[3]]])
    base=[(base_pixels[0]-bounds[0])/scale,(base_pixels[1]-bounds[1])/scale]
    footprint=[(max(p[0] for p in feet)-min(p[0] for p in feet))/scale,(max(p[1] for p in feet)-min(p[1] for p in feet))/scale]
    nearest=profile.pop('contact_pixels',max(feet,key=lambda p:p[1]))
    contact=[(nearest[i]-bounds[i])/scale for i in range(2)]
    # Panasonic/PVM/Old TV prepared GLBs are in metres. Retro is artist-scaled (~2 m high);
    # use an explicit approximate 450 mm cabinet, preserving all its proportions.
    height_mm=450.0 if identifier=='retro' else profile['source_size_metres'][2]*1000
    units_per_mm=profile['native_height']/height_mm
    if not (0<base[0]<display[0] and 0<base[1]<display[1]):
        raise ValueError(f'{identifier} floor point leaves the TV render')
    profile.update(quad=quad,size=list(crop.size),display=display,base=base,footprint=footprint,contact=contact,
                   cabinet_height_mm=height_mm,units_per_mm=units_per_mm,
                   scale_basis='Approximate 450 mm cabinet height' if identifier=='retro' else 'Prepared source metres',label=label,
                   image_sha256=hashlib.sha256((out/f'{identifier}.png').read_bytes()).hexdigest())
    prepared=ROOT/'third_party/models'/family;prepared.mkdir(parents=True,exist_ok=True)
    (prepared/'source.json').write_text(json.dumps(profile,indent=2)+'\n',newline='\n')
    # The Panasonic keeps its original stage/tv/profile.json name.
    name='profile.json' if identifier=='panasonic' else f'{identifier}.json'
    (out/name).write_text(json.dumps(profile,indent=2)+'\n',newline='\n')
    return dict(id=identifier,image=f'stage/tv/{identifier}.png',aspect=crop.width/crop.height,quad=quad,
                display=display,base=base,footprint=footprint,contact=contact,units_per_mm=units_per_mm,
                label=label,license=profile['license'],author=profile['author'],source=profile['source'])


def build():
    from . import floor
    floor.build()                       # shared floor glow and contact shadow
    registry=[prepare(*p) for p in PROFILES]
    out=ROOT/'theme/art-book-slot/_slot/stage/tv'
    (out/'profiles.json').write_text(json.dumps(dict(default=registry[0]['id'],profiles=registry),indent=2)+'\n',newline='\n')
    lines=['// Generated by tools.themebuild.television. Panasonic CRT TV by DamianToons, CC BY 4.0;',
           '// TV, Old TV, Retro TV by Denys Hroshko, CC BY-NC 4.0 (noncommercial). See MODEL_CREDITS.txt.',
           '// Sony PVM-1341 by dark_igorek, CC BY 4.0. Old TV by pibanezl, CC BY 4.0.',
           '#pragma once','typedef struct SlotTelevisionProfile { const char* id; const char* image; float aspect; float quad[8]; float display[2]; float base[2]; float footprint[2]; float contact[2]; float units_per_mm; } SlotTelevisionProfile;',
           'static const SlotTelevisionProfile slotTelevisions[]={']
    for p in registry:
        values=','.join(f'{v:.8f}f' for point in p['quad'] for v in point)
        extra=','.join(f'{{{a:.4f}f,{b:.4f}f}}' for a,b in (p['display'],p['base'],p['footprint'],p['contact']))+f',{p["units_per_mm"]:.8f}f'
        lines.append(f'    {{"{p["id"]}","{p["image"]}",{p["aspect"]:.8f}f,{{{values}}},{extra}}},')
    lines+=['};','']
    (ROOT/'tools/frontend/overlay/es-app/src/components/SlotTelevision.h').write_text('\n'.join(lines),newline='\n')
    print('Prepared TVs:',', '.join(f'{p["id"]} {p["aspect"]:.3f}' for p in registry))
    return registry


if __name__=='__main__':build()
