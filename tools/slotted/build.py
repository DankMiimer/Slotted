def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')


def build(out=SLOTTED_SOURCE):
    tv = out / '_tv'
    for stick, shape in [('l3', 'M12 8v16h12'), ('r3', 'M10 24V8h8q6 0 6 5t-6 5h-8m7 0 7 6')]:
        write(tv / f'help-{stick}.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 32"><g fill="none" stroke="white" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round"><rect x="1.5" y="1.5" width="45" height="29" rx="8"/><path d="' + shape + 'M31 8h7v8h-6m6 0v8h-7"/></g></svg>\n')
    write(out / 'theme.xml', theme_xml())
    write(out / 'splash.xml', splash_xml())
    write(tv / 'gamelist.xml', gamelist_xml())
    write(tv / 'system.xml', system_xml())
    write(tv / 'menu.xml', menu_xml())
    # ClockComponent/BatteryText update their own visibility; hiding legacy extras
    # after importing them cannot prevent duplicate status. Import the retained shelf
    # without its global status include, then apply Slotted's own carousel status.
    carousel = (LEGACY_SOURCE / '_slot/shelf-common.xml').read_text(encoding='utf-8')
    marker = '<include>./status.xml</include>'
    if carousel.count(marker) != 1:
        raise ValueError('Shared carousel status include changed; review the Slotted adapter')
    carousel = carousel.replace(marker, '').replace('>./', '>${themePath}/_slot/')
    carousel = carousel.replace('</theme>', status('gamecarousel') + '</theme>')
    write(tv / 'carousel.xml', carousel)
    for skin in SKINS:
        write(tv / f'skin-{skin}.xml', skin_xml(skin))
        header(skin).save(tv / f'header-{skin}.png')
    for system, model in SYSTEMS.items():
        write(out / system / 'theme.xml', system_folder_xml(system, model))
    frame().save(tv / 'frame.png')
    scanlines().save(tv / 'scan.png')
    test_card(CARD[2], CARD[3]).save(tv / 'card.png')
    splash().save(tv / 'splash.png')
    icons = tv / 'icons'
    icons.mkdir(parents=True, exist_ok=True)
    for name, level in (('full', 1), ('at75', .75), ('at50', .5), ('at25', .25), ('empty', 0)):
        battery(level).save(icons / f'battery-{name}.png')
    battery(.5, True).save(icons / 'battery-charging.png')
    fonts = tv / 'fonts'
    fonts.mkdir(parents=True, exist_ok=True)
    shutil.copy2(RASTER_ES, fonts / 'RasterForge.ttf')
    shutil.copy2(ROOT / 'third_party/raster-forge/LICENSE-CC0.txt', fonts / 'RasterForge-LICENSE-CC0.txt')
    for name, body in NETWORK.items():
        write(out / '_inc/images' / name, f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">{body}</svg>\n')
    shutil.copy2(LEGACY_SOURCE / 'collections.info', out / 'collections.info')
    shutil.copy2(ROOT / 'LICENSE', out / 'LICENSE')
    PREVIEW.mkdir(parents=True, exist_ok=True)
    for skin in SKINS:
        preview(skin).convert('RGB').save(PREVIEW / f'preview-gamelist-{skin}.png')
    print('built', out)


if __name__ == '__main__':
    build()
