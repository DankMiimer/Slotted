def p(x, y):
    return f'<pos>{x / W:.6f} {y / H:.6f}</pos>'


def s(w, h):
    return f'<size>{w / W:.6f} {h / H:.6f}</size>'


def box(x, y, w, h):
    return p(x, y) + s(w, h)


def font(px):
    small, large = FONT_SIZES[px]
    return (f'<fontPath>{FONT}</fontPath><fontSize>{small}</fontSize>'
            f'<fontSize if="${{screen.height}} &gt;= 720">{large}</fontSize>')


def xml(body, root='<theme>'):
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by tools/slotted/build.py; edit the '
            'builder, not this file. -->\n' + root + '\n   <formatVersion>7</formatVersion>\n' + body + '</theme>\n')


