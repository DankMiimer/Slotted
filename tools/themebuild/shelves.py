"""Writes the per-system gamecarousel shelves and the per-system theme.xml files.

Carousel sizes (logoSize, logoPos) are normalised to the carousel's own size, item template
children to the item's size, and everything else to the screen.

The carousel is three cart-pitches wide and centred, so with maxLogoCount 3 its pitch equals the
cart width (Slot's spacing) and neighbours run off both screen edges.
"""
from .geometry import CAROUSEL_H, H, ROOT, SIDE_BRIGHTNESS, SIDE_SCALE, SYSTEMS, W
from .video import shader_xml, surface_binding, build_variants

# ES uses easeOutQuint. 650 ms gives ~39 presentation opportunities at 60 Hz
# rather than ~30 at 500 ms, while its first 90% moves in about 240 ms. Actual
# presentation pacing still depends on the frontend; duration does not raise fps.
SLIDE_MS = 650

# The preview needs a gamelist <video> link: Scarab evaluates expressions only
# for String properties, and a video path is a Path, so firstfile() fallbacks
# would be read as a literal file name (tested on device, 2026-10-14).


def lighting(colour='FFFFFF'):
    """Dim RGB, keeping the moving cart opaque and its default face fully lit.

    ES can recreate a selected item after a game without replaying its activation.
    A bright default fixes that directly, without a second stationary cart image.
    """
    dark = ''.join(f'{round(int(colour[i:i+2], 16)*SIDE_BRIGHTNESS):02X}' for i in (0, 2, 4))
    return f"""<opacity>1</opacity>
               <color>{colour}FF</color>
               <storyboard event="activate">
                  <animation property="color" from="{colour}FF" to="{colour}FF" duration="1"/>
               </storyboard>
               <storyboard event="deactivate">
                  <animation property="color" from="{dark}FF" to="{dark}FF" duration="1"/>
               </storyboard>
               <storyboard event="scroll">
                  <animation property="color" from="{dark}FF" to="{dark}FF" duration="1"/>
               </storyboard>"""

SHELF = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/themebuild ({name}): {w}x{h} carts resting at y={top:g}..{foot:g}, {shell} shell. -->
<theme>
   <formatVersion>7</formatVersion>
   <view name="gamecarousel">
{band_override}      <gamecarousel name="gamecarousel">
         <type>horizontal</type>
         <pos>{cx} 0</pos>
         <size>{cw} {ch}</size>
         <color>00000000</color>
         <logoSize>{lw} {lh}</logoSize>
         <logoScale>{scale}</logoScale>
         <logoPos>{lx} {ly}</logoPos>
         <logoAlignment>bottom</logoAlignment>
         <maxLogoCount>3</maxLogoCount>
         <minLogoOpacity>1</minLogoOpacity>
         <transitionSpeed>{slide_ms}</transitionSpeed>
         <defaultTransition>slide</defaultTransition>
         <zIndex>20</zIndex>
         <itemTemplate>
            <image name="backing">
               <autoFade>false</autoFade>
               <path>firstfile(directory({{game:path}}) + "/media/slotcarts/" + stem({{game:path}}) + ".back.png", "${{currentPath}}/backings/{shell}.png")</path>
            </image>
            <image name="cart">
               <autoFade>false</autoFade>
               <path>firstfile(directory({{game:path}}) + "/media/slotcarts/" + stem({{game:path}}) + ".png", "${{currentPath}}/shells/{shell}.png")</path>
               {dim}
            </image>
            <image name="logo">
               <autoFade>false</autoFade>
               <origin>0.5 0.5</origin>
               <pos>{wcx} {wcy}</pos>
               <maxSize>{lmw} {lmh}</maxSize>
               <path>{{game:marquee}}</path>
               <visible>!exists(directory({{game:path}}) + "/media/slotcarts/" + stem({{game:path}}) + ".png")</visible>
               {dim}
            </image>
            <image name="paper">
               <autoFade>false</autoFade>
               <pos>{wx} {wy}</pos>
               <size>{ww} {wh}</size>
               <path>${{currentPath}}/px.png</path>
               <visible>!exists(directory({{game:path}}) + "/media/slotcarts/" + stem({{game:path}}) + ".png") &amp;&amp; !exists({{game:marquee}})</visible>
               {paper_dim}
            </image>
            <text name="title">
               <pos>{tx} {ty}</pos>
               <size>{tw} {th}</size>
               <text>{{game:nameShort}}</text>
               <fontPath>${{currentPath}}/fonts/OpenSans-SemiBold.ttf</fontPath>
               <fontSize>{font}</fontSize>
               <fontSize if="${{screen.height}} &gt;= 720">{font_hd}</fontSize>
               <alignment>center</alignment>
               <verticalAlignment>center</verticalAlignment>
               <visible>!exists(directory({{game:path}}) + "/media/slotcarts/" + stem({{game:path}}) + ".png") &amp;&amp; !exists({{game:marquee}})</visible>
               {text_dim}
            </text>
         </itemTemplate>
      </gamecarousel>
      <!-- The selected ROM alone plays after resting on the shelf for three seconds.
           Its complete label is replaced with uniformly scaled, cropped video. -->
      <!-- The built-in md_video stays disabled in shelf-common. One persistent
           extra video binds to the cursor. Rebinding enabled resets the delay,
           even when adjacent games share a clip. Keeping it outside animated
           detail containers avoids per-selection player recreation. -->
      <video name="slot_video" extra="true" ifSubset="slot-video:on">
         <path>{{game:video}}</path>
         <enabled>exists({{game:video}})</enabled>
         <visible>exists({{game:video}})</visible>
         <origin>0.5 0.5</origin>
         <pos>{vcx} {vcy}</pos>
         <minSize>{vw} {vh}</minSize>
         <delay>3</delay>
         <effect>none</effect>
         <audio>false</audio>
         <showSnapshotDelay>false</showSnapshotDelay>
         <showSnapshotNoVideo>false</showSnapshotNoVideo>
         <zIndex>22</zIndex>
{surface_binding}{video_shader}      </video>
   </view>
</theme>
"""

SYSTEM = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/themebuild: {system} gets the {shelf} shelf; everything else is Art Book Next. -->
<theme>
   <formatVersion>7</formatVersion>
   <include>./../theme.xml</include>
   <include ifSubset="slot-{family}:on">./../_slot/shelf-common.xml</include>
   <include ifSubset="slot-{family}:on">./../_slot/shelf-{shelf}.xml</include>
</theme>
"""


def n(v):
    return f'{v:.6f}'.rstrip('0').rstrip('.')


def shelf_xml(key, shape, shell_name):
    w, h = shape.size
    cw = 3 * w
    cx = W / 2 - cw / 2
    lw, lh = w * SIDE_SCALE, h * SIDE_SCALE
    x0, y0, x1, y1 = shape.well
    # The shader reads the same integer label bounds as the baker and crops
    # inside the full media canvas. This also permits per-ROM surface variants.
    vx0,vy0,vx1,vy1 = 0,0,1,1
    pad = 0.06
    result = SHELF.format(
        name=key, w=w, h=h, top=shape.top, foot=shape.foot, shell=shell_name, dim=lighting(),
        paper_dim=lighting('E9E4D8'), text_dim=lighting('1A1816'),
        slide_ms=SLIDE_MS,
        band_override='',
        cx=n(cx / W), cw=n(cw / W), ch=n(CAROUSEL_H / H),
        lw=n(lw / cw), lh=n(lh / CAROUSEL_H), scale=n(1 / SIDE_SCALE),
        # The selected item's bottom-centre lands at (screen centre, foot).
        lx=n((cw / 2 - lw / 2) / cw), ly=n((shape.foot - lh) / CAROUSEL_H),
        # The mask preserves rounded plastic corners; the full label is replaced.
        vcx=n((W / 2 - w / 2 + w*(vx0+vx1)/2) / W),
        vcy=n((shape.top + h*(vy0+vy1)/2) / H),
        vw=n((round(w*vx1)-round(w*vx0)) / W),
        vh=n((round(h*vy1)-round(h*vy0)) / H),
        video_shader=shader_xml(shape),
        surface_binding=surface_binding(shape),
        wcx=n((x0 + x1) / 2), wcy=n((y0 + y1) / 2),
        lmw=n((x1 - x0) * (1 - 2 * pad)), lmh=n((y1 - y0) * (1 - 2 * pad)),
        wx=n(x0), wy=n(y0), ww=n(x1 - x0), wh=n(y1 - y0),
        tx=n(x0 + (x1 - x0) * pad), ty=n(y0 + (y1 - y0) * pad),
        tw=n((x1 - x0) * (1 - 2 * pad)), th=n((y1 - y0) * (1 - 2 * pad)),
        # ~22 px on the panel: 17 x FontScale 1.31 (see shelf-common.xml); unscaled from 720 up.
        font='0.03542', font_hd=n(33 / 720),
    )
    if key not in ('psx','dreamcast','psp'):
        console='md' if key in ('megadrive','genesis') else key
        path='./band-console-'+console+'.png'
        if console=='snes':
            path='contains(upper({game:path}), "(USA") || contains(upper({game:path}), "(CANADA") ? "${currentPath}/band-console-snes-us.png" : "${currentPath}/band-console-snes.png"'
        elif console=='md':
            path='contains(upper({game:path}), "JAPAN") &amp;&amp; !contains(upper({game:path}), "USA") &amp;&amp; !contains(upper({game:path}), "EUROPE") ? "${currentPath}/band-console-md-jp.png" : "${currentPath}/band-console-md.png"'
        result=result.replace('      <gamecarousel name="gamecarousel">',
            '      <image name="slot-band" extra="true"><path>'+path+'</path></image>\n'
            '      <text name="slot-name" extra="true"><visible>false</visible></text>\n'
            '      <gamecarousel name="gamecarousel">')
    if shape.name in ('psx','dreamcast','psp'):
        band_name='band-psx' if shape.name=='psx' else 'band-console-'+shape.name
        result=result.replace('      <gamecarousel name="gamecarousel">',
            f'      <image name="slot-band" extra="true"><path>./{band_name}.png</path></image>\n'
            '      <text name="slot-name" extra="true"><visible>false</visible></text>\n'
            '      <gamecarousel name="gamecarousel">')
        start=result.index('            <image name="paper">');end=result.index('            <text name="title">',start)
        result=result[:start]+result[end:]
        result=result.replace(lighting('1A1816'),lighting('F4F1EA'))
    return result


def build(theme_dir, shapes):
    slot = theme_dir / '_slot'
    build_variants(slot)
    shelves = {}
    alternate=shelf_xml('snes',shapes['snes-tzakol'],'snes-tzakol')
    alternate=alternate.replace('+ ".png"','+ ".tzakol.png"').replace('+ ".back.png"','+ ".tzakol.back.png"')
    (slot/'shelf-snes-tzakol.xml').write_text(alternate,encoding='utf-8',newline='\n')
    for system, (shape_name, shell_name) in SYSTEMS.items():
        key = shell_name if shape_name == shell_name else f'{shape_name}-{shell_name}'
        if key not in shelves:
            shelves[key] = shelf_xml(key, shapes[shape_name], shell_name)
            (slot / f'shelf-{key}.xml').write_text(shelves[key], encoding='utf-8', newline='\n')
        folder = theme_dir / system
        folder.mkdir(exist_ok=True)
        (folder / 'theme.xml').write_text(SYSTEM.format(system=system, shelf='${slotSnesCartridgeShelf}' if system in ('snes','snesh') else key,
                                                      family='megadrive' if system == 'genesis' else system.rstrip('h')),
                                          encoding='utf-8', newline='\n')
